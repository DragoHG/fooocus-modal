"""Guardrail tests for the authorship push checker."""

from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHECKER = ROOT / "scripts" / "check_git_authorship.sh"


class AuthorshipScriptTests(unittest.TestCase):
    def test_checker_passes_on_head(self) -> None:
        proc = subprocess.run(
            [str(CHECKER)],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertIn("ok", proc.stdout.lower())

    def test_banned_em_dash_in_message_detected(self) -> None:
        # Simulate grep pattern used by the checker against a temp file body.
        body = "feat: something — with em dash\n"
        import re

        banned = re.compile(
            r"co-authored-by:\s*cursor|cursoragent@|generated by|@cursor\.com|"
            r"copilot|chatgpt|claude\.ai|openai|—|–|…",
            re.I,
        )
        self.assertTrue(banned.search(body))


if __name__ == "__main__":
    unittest.main()
