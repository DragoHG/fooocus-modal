#!/usr/bin/env bash
# Validate that commits match sole-maintainer authorship and clean provenance.
# Usage:
#   scripts/check_git_authorship.sh              # HEAD only
#   scripts/check_git_authorship.sh <commit>     # one commit
#   scripts/check_git_authorship.sh <a> <b>      # exclusive range a..b (like pre-push)
set -euo pipefail

EXPECTED_NAME="DragoHG"
EXPECTED_EMAIL="fabio.monreal@outlook.com"

# Case-insensitive patterns that must never appear in commit subjects/bodies.
BANNED_MSG_RE='co-authored-by:[[:space:]]*cursor|cursoragent@|generated by|@cursor\.com|copilot|chatgpt|claude\.ai|openai|—|–|…'

die() {
  printf 'authorship-check: %s\n' "$*" >&2
  exit 1
}

check_commit() {
  local sha="$1"
  local an ae cn ce body

  an=$(git log -1 --format='%an' "$sha")
  ae=$(git log -1 --format='%ae' "$sha")
  cn=$(git log -1 --format='%cn' "$sha")
  ce=$(git log -1 --format='%ce' "$sha")
  body=$(git log -1 --format='%B' "$sha")

  if [[ "$an" != "$EXPECTED_NAME" ]]; then
    die "commit ${sha:0:7}: author name '$an' != '$EXPECTED_NAME'"
  fi
  if [[ "$ae" != "$EXPECTED_EMAIL" ]]; then
    die "commit ${sha:0:7}: author email '$ae' != '$EXPECTED_EMAIL'"
  fi
  if [[ "$ce" != "$EXPECTED_EMAIL" ]]; then
    die "commit ${sha:0:7}: committer email '$ce' != '$EXPECTED_EMAIL' (refuse tooling committers)"
  fi
  if printf '%s' "$body" | grep -Eiq "$BANNED_MSG_RE"; then
    die "commit ${sha:0:7}: message contains banned tooling/provenance text"
  fi
  if printf '%s' "$an$ae$cn$ce" | grep -Eiq 'cursor|cursoragent|copilot'; then
    die "commit ${sha:0:7}: author/committer identity looks like tooling"
  fi
}

zero=0000000000000000000000000000000000000000

if [[ $# -eq 0 ]]; then
  check_commit HEAD
elif [[ $# -eq 1 ]]; then
  check_commit "$1"
elif [[ $# -eq 2 ]]; then
  local_old="$1"
  local_new="$2"
  if [[ "$local_new" == "$zero" ]]; then
    exit 0
  fi
  if [[ "$local_old" == "$zero" ]]; then
    # New branch / first push: every reachable commit.
    mapfile -t shas < <(git rev-list "$local_new")
  else
    mapfile -t shas < <(git rev-list "${local_old}..${local_new}")
  fi
  if [[ ${#shas[@]} -eq 0 ]]; then
    exit 0
  fi
  for sha in "${shas[@]}"; do
    check_commit "$sha"
  done
else
  die "usage: $0 [<commit> | <old> <new>]"
fi

printf 'authorship-check: ok (%s <%s>)\n' "$EXPECTED_NAME" "$EXPECTED_EMAIL"
